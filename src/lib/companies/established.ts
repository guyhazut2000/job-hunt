/** Drop the `hub` tag (kept here only for reporting) before merging into the shared lists. */
export function withoutHub<T extends { hub: Hub }>(c: T): Omit<T, "hub"> {
  const rest: Partial<T> = { ...c };
  delete rest.hub;
  return rest as Omit<T, "hub">;
}
