export function jobsMapStrings(locale: Locale): JobsMapStrings {
  return locale === "he" ? he : en;
}

export const fillN = (s: string, vars: Record<string, string | number>) =>
  s.replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? ""));

/** "12 min", "1 h 05 min". */
export function formatDuration(seconds: number, s: Pick<JobsMapStrings, "minutes" | "hours">): string {
  const m = Math.max(1, Math.round(seconds / 60));
  if (m < 60) return fillN(s.minutes, { n: m });
  return fillN(s.hours, { h: Math.floor(m / 60), m: String(m % 60).padStart(2, "0") });
}
