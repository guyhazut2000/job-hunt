export type LearningStrings = typeof he;

export function learningStrings(locale: Locale): LearningStrings {
  return locale === "en" ? en : he;
}

/** Tiny {placeholder} formatter shared by the learning UI. */
export function fmt(s: string, params: Record<string, string | number>): string {
  return s.replace(/\{(\w+)\}/g, (m, k: string) => (k in params ? String(params[k]) : m));
}
